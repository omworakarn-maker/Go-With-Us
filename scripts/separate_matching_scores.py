def replace(p, text):
    p.clear()
    r = p.add_run(text)
    r.font.name = 'TH SarabunPSK'
    r.font.size = Pt(16)
    for k in ('ascii', 'hAnsi', 'eastAsia', 'cs'):
        r._element.get_or_add_rPr().rFonts.set(qn('w:' + k), 'TH SarabunPSK')

def after(p, text):
    el = deepcopy(p._p)
    p._p.addnext(el)
    n = Paragraph(el, p._parent)
    replace(n, text)
    return n

